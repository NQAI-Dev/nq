/*
 * nq — text rendering (procedural 5x7 font).
 *
 * Renders ASCII text by drawing each glyph pixel as a small filled
 * rectangle. Quality is intentionally low (one fill_rect call per
 * glyph pixel = 35 rects per character) but no asset file is needed
 * so the example works on a fresh checkout without any fixture.
 *
 * A real game would replace this with TTF rasterization (SDL3_ttf or
 * stb_truetype) and a baked glyph cache. The NqText API stays the
 * same; only the internals change.
 *
 * Coverage: ASCII 0x20..0x7E (95 printable glyphs). Anything outside
 * renders as '?'. Lowercase letters use distinct shapes from uppercase;
 * not 5x7 perfect, but recognizable.
 */
