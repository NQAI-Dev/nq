struct NqText {
    NqRenderer *renderer;
    uint8_t    color[4];
};

NqText *nq_text_create(NqRenderer *ren) {
    if (!ren) return NULL;
    NqText *t = calloc(1, sizeof(NqText));
    if (!t) return NULL;
    t->renderer = ren;
    t->color[0] = 255; t->color[1] = 255; t->color[2] = 255; t->color[3] = 255;
    return t;
}

void nq_text_destroy(NqText *t) {
    free(t);
}

void nq_text_set_color(NqText *t, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (!t) return;
    t->color[0] = r;
    t->color[1] = g;
    t->color[2] = b;
    t->color[3] = a;
}

/* Render one glyph's worth of pixels. The bit test inverts vertically
 * (row 0 in the array is the top of the glyph, so MSB-first row data
 * scans the top first). */
static void nq_text_render_glyph(NqRenderer *ren, int x, int y,
                                const uint8_t *bits,
                                uint8_t r, uint8_t g, uint8_t b) {
    for (int row = 0; row < NQ_TEXT_GLYPH_H; row++) {
        uint8_t row_bits = bits[row];
        for (int col = 0; col < NQ_TEXT_GLYPH_W; col++) {
            /* MSB = leftmost pixel. */
            if (row_bits & (1 << (NQ_TEXT_GLYPH_W - 1 - col))) {
                nq_renderer_fill_rect(ren,
                    NQ_COLOR_RGB(r, g, b),
                    x + col * NQ_TEXT_SCALE,
                    y + row * NQ_TEXT_SCALE,
                    NQ_TEXT_SCALE,
                    NQ_TEXT_SCALE);
            }
        }
    }
}

static const uint8_t *nq_text_glyph_for(char c) {
    unsigned char cp = (unsigned char)c;
    if (cp < 0x20 || cp > 0x7E) {
        /* Out of printable range → render '?' at 0x3F. */
        return NQ_TEXT_FONT['?' - 0x20];
    }
    return NQ_TEXT_FONT[cp - 0x20];
}

int nq_text_draw(NqText *t, const char *s, int x, int y) {
    if (!t || !s) return x;
    int cur_x = x;
    int cur_y = y;
    for (const char *p = s; *p; p++) {
        if (*p == '\n') {
            cur_x = x;
            cur_y += NQ_TEXT_ADV_H * NQ_TEXT_SCALE;
            continue;
        }
        const uint8_t *bits = nq_text_glyph_for(*p);
        nq_text_render_glyph(t->renderer,
            cur_x, cur_y, bits,
            t->color[0], t->color[1], t->color[2]);
        cur_x += NQ_TEXT_ADV_W * NQ_TEXT_SCALE;
    }
    return cur_x;
}

int nq_text_width(NqText *t, const char *s) {
    if (!t || !s) return 0;
    int max_w = 0;
    int cur_w = 0;
    for (const char *p = s; *p; p++) {
        if (*p == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
            continue;
        }
        cur_w += NQ_TEXT_ADV_W * NQ_TEXT_SCALE;
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}

int nq_text_glyph_w(NqText *t, char c) {
    (void)t; (void)c;
    return NQ_TEXT_GLYPH_W * NQ_TEXT_SCALE;
}

int nq_text_glyph_h(NqText *t, char c) {
    (void)t; (void)c;
    return NQ_TEXT_GLYPH_H * NQ_TEXT_SCALE;
}

int nq_text_line_h(NqText *t) {
    (void)t;
    return NQ_TEXT_ADV_H * NQ_TEXT_SCALE;
}
